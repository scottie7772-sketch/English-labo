import assert from 'node:assert/strict';
import { readScriptJa, planScriptJa } from '../video-script-ja.js';
import { cueStamps, planJaWrites, videoJaView } from '../video-ja.js';

const cues = lines => lines.map((en, i) => ({id: String(i), en, start: i, end: i + 1}));
const plan = (lines, rows, title) => planScriptJa(cues(lines), readScriptJa(rows, 'ma', title));
const rows = lines => lines.map((en, i) => ({en, ja: '訳' + i}));
const context = ['A unique opening.', 'Yes.', 'Yes.', 'The middle scene arrives.', 'Yes.', 'The final scene closes.'];
const repeated = plan(context, rows(context));
assert.equal(repeated.patch.size, 6);
assert.equal(repeated.patch.get('2')[0].ja, '訳2');
assert.equal(repeated.patch.get('4')[0].ja, '訳4');
assert.equal(plan(['Yes.', 'Yes.'], rows(['Yes.'])).patch.size, 0);
assert.equal(plan(['We’re ready!'], rows(['WE\'RE READY.'])).patch.size, 1);
assert.equal(plan(['Were ready.'], rows(["We're ready."])).patch.size, 0);
const split = plan(['She opened the door.', 'Then she left.'], [{en:['She opened the door','then she left'], ja:'彼女は扉を開けて去った。'}]);
assert.deepEqual(split.patch.get('1')[0].cueIds,['0','1']);
const joined = plan(['She opened the door. Then she left.'],rows(['She opened the door.','Then she left.']));
assert.deepEqual(joined.patch.get('0').map(v=>v.ja),['訳0','訳1']);
const chapter = ['CHAPTER 1','Same sentence here.','First chapter ending.','CHAPTER 2','Same sentence here.','Second chapter ending.'];
assert.deepEqual([...plan(chapter,{chapter:2,items:rows(['Same sentence here.'])}).patch.keys()],['4']);
assert.equal(plan(chapter,rows(['Same sentence here.'])).review.length, 1);
assert.equal(plan(chapter,{chapter:3,items:rows(['First chapter ending.'])}).patch.size, 0);
assert.equal(plan(chapter,[{en:'First chapter ending. CHAPTER 2 Same sentence here.',ja:'誤結合'}]).patch.size,0);
assert.throws(()=>plan(['Same sentence here.'],{chapter:1,items:rows(['Same sentence here.'])},'MA_CHAPTER_02'),/章/);
assert.throws(()=>plan(['A'],{materialId:'elsewhere',items:rows(['A'])}),/教材ID/);
assert.equal(plan(['A missing comparison.'],rows(['Different text.'])).review[0].number,1);
assert.equal(plan(context,rows(context.slice().reverse())).patch.size,0);
const base = cues(['A distinct sentence.','Some other text.']);
const expected = cueStamps(base);
const prior = planJaWrites('ma',base,[],plan(base.map(c=>c.en),rows(base.map(c=>c.en))).patch,expected);
const deletion = plan(base.map(c=>c.en),[{en:base[0].en,ja:''}]);
const stored = new Map(prior.puts);
const changes = planJaWrites('ma',base,[...stored.values()],deletion.patch,expected);
for (const id of changes.deletes) stored.delete(id);
for (const [id,row] of changes.puts) stored.set(id,row);
assert.equal(videoJaView(base,[...stored.values()]).get(base[0]),'');
assert.equal(videoJaView(base,[...stored.values()]).get(base[1]),'訳1');
console.log('Script JA matching passed: repetitions, punctuation, split/join, gaps, chapters, scope, and targeted delete');
